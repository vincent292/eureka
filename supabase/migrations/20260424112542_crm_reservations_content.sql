create or replace function public.ensure_booking_slot_available()
returns trigger
language plpgsql
as $$
declare
  overlapping_count integer;
  max_capacity integer;
  slot_weekday integer;
  slot_time time;
  slot_end_time time;
begin
  new.ends_at = new.starts_at + make_interval(mins => new.duration_minutes);

  if new.status not in ('pending_payment', 'confirmed') then
    return new;
  end if;

  slot_weekday = extract(dow from new.starts_at at time zone 'America/La_Paz');
  slot_time = (new.starts_at at time zone 'America/La_Paz')::time;
  slot_end_time = (new.ends_at at time zone 'America/La_Paz')::time;

  if not exists (
    select 1
    from public.booking_availability_rules rule
    where rule.weekday = slot_weekday
      and rule.is_open = true
      and slot_time >= rule.opens_at
      and slot_end_time <= rule.closes_at
  ) then
    raise exception 'Horario fuera de atencion';
  end if;

  if exists (
    select 1
    from public.booking_blackouts blackout
    where new.starts_at < blackout.ends_at
      and new.ends_at > blackout.starts_at
  ) then
    raise exception 'Horario bloqueado por administracion';
  end if;

  max_capacity = public.booking_capacity();

  select count(*)
  into overlapping_count
  from public.bookings booking
  where booking.id <> new.id
    and booking.status in ('pending_payment', 'confirmed')
    and (booking.status = 'confirmed' or booking.expires_at > now())
    and new.starts_at < booking.ends_at
    and new.ends_at > booking.starts_at;

  if overlapping_count >= max_capacity then
    raise exception 'Horario sin cupos disponibles';
  end if;

  return new;
end;
$$;

drop trigger if exists ensure_booking_slot_available on public.bookings;
create trigger ensure_booking_slot_available
before insert or update of starts_at, duration_minutes, status
on public.bookings
for each row execute function public.ensure_booking_slot_available();

create or replace function public.enqueue_booking_notification()
returns trigger
language plpgsql
as $$
declare
  message text;
begin
  if tg_op = 'INSERT' then
    message = 'Gracias por reservar en Eureka. Tu codigo de reserva es ' || new.reservation_code ||
      '. Para cambiar tu horario una sola vez, usa este codigo en la pagina.';
  elsif old.status is distinct from new.status and new.status = 'confirmed' then
    message = 'Tu reserva en Eureka fue confirmada. Codigo: ' || new.reservation_code ||
      '. Te esperamos el ' || to_char(new.starts_at at time zone 'America/La_Paz', 'DD/MM/YYYY HH24:MI') || '.';
  elsif old.status is distinct from new.status and new.status = 'rejected' then
    message = 'Tu reserva en Eureka no pudo ser verificada. El horario se liberara si no confirmas el pago nuevamente.';
  elsif old.starts_at is distinct from new.starts_at then
    message = 'Tu reserva en Eureka fue cambiada. Nuevo horario: ' ||
      to_char(new.starts_at at time zone 'America/La_Paz', 'DD/MM/YYYY HH24:MI') ||
      '. Codigo: ' || new.reservation_code || '.';
  else
    return new;
  end if;

  insert into public.notification_events (booking_id, event_type, recipient, message)
  values (new.id, lower(tg_op) || '_booking', new.phone, message);

  return new;
end;
$$;

