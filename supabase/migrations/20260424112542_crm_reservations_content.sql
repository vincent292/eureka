create or replace function public.reschedule_booking_once(
  p_reservation_code text,
  p_phone text,
  p_starts_at timestamptz,
  p_duration_minutes integer
)
returns table (
  booking_id uuid,
  reservation_code text,
  starts_at timestamptz,
  ends_at timestamptz,
  status public.booking_status
)
language plpgsql
security definer
set search_path = public
as $$
declare
  target_booking public.bookings;
begin
  select *
  into target_booking
  from public.bookings booking
  where booking.reservation_code = upper(trim(p_reservation_code))
    and booking.phone = trim(p_phone)
    and booking.status in ('pending_payment', 'confirmed')
  for update;

  if target_booking.id is null then
    raise exception 'Reserva no encontrada';
  end if;

  if target_booking.change_used then
    raise exception 'El cambio de horario ya fue utilizado';
  end if;

  if now() > target_booking.change_expires_at then
    raise exception 'El codigo de cambio ya expiro';
  end if;

  update public.bookings
  set starts_at = p_starts_at,
      duration_minutes = p_duration_minutes,
      status = 'pending_payment',
      change_used = true,
      expires_at = now() + interval '10 minutes',
      confirmed_at = null,
      rejected_at = null
  where id = target_booking.id
  returning * into target_booking;

  return query
  select
    target_booking.id,
    target_booking.reservation_code,
    target_booking.starts_at,
    target_booking.ends_at,
    target_booking.status;
end;
$$;

create or replace function public.expire_pending_bookings()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  affected_count integer;
begin
  update public.bookings
  set status = 'expired'
  where status = 'pending_payment'
    and expires_at <= now();

  get diagnostics affected_count = row_count;
  return affected_count;
end;
$$;

create or replace view public.public_booking_slots as
select
  starts_at,
  ends_at,
  count(*) filter (
    where status = 'confirmed'
      or (status = 'pending_payment' and expires_at > now())
  ) as used_capacity,
  public.booking_capacity() as max_capacity
from public.bookings
where status in ('pending_payment', 'confirmed')
group by starts_at, ends_at;

